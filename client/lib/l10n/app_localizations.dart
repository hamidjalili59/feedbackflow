import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';

class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = <Locale>[
    Locale('fa'),
    Locale('en'),
    Locale('zh'),
  ];

  static const localizationsDelegates = <LocalizationsDelegate<dynamic>>[
    AppLocalizationsDelegate(),
    GlobalMaterialLocalizations.delegate,
    GlobalCupertinoLocalizations.delegate,
    GlobalWidgetsLocalizations.delegate,
  ];

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  TextDirection get textDirection =>
      locale.languageCode == 'fa' ? TextDirection.rtl : TextDirection.ltr;

  String get languageName => switch (locale.languageCode) {
    'fa' => 'فارسی',
    'zh' => '中文',
    _ => 'English',
  };

  String t(String key) {
    return _localizedValues[locale.languageCode]?[key] ??
        _localizedValues['en']?[key] ??
        key;
  }

  String fieldType(String wireValue) {
    return _localizedValues[locale.languageCode]?['field.$wireValue'] ??
        _localizedValues['en']?['field.$wireValue'] ??
        _humanizeWireValue(wireValue);
  }

  String enumLabel(String wireValue) {
    return _localizedValues[locale.languageCode]?['enum.$wireValue'] ??
        _localizedValues['en']?['enum.$wireValue'] ??
        _humanizeWireValue(wireValue);
  }

  String countForms(int count) => switch (locale.languageCode) {
    'fa' => '$count فرم',
    'zh' => '$count 个表单',
    _ => '$count forms',
  };

  String countFields(int count) => switch (locale.languageCode) {
    'fa' => '$count فیلد',
    'zh' => '$count 个字段',
    _ => '$count fields',
  };

  String countSubmissions(int count) => switch (locale.languageCode) {
    'fa' => '$count پاسخ',
    'zh' => '$count 份提交',
    _ => '$count submissions',
  };

  static String _humanizeWireValue(String value) {
    if (value.trim().isEmpty) return value;
    return value
        .replaceAll('_', ' ')
        .split(' ')
        .map((part) {
          if (part.isEmpty) return part;
          return '${part[0].toUpperCase()}${part.substring(1)}';
        })
        .join(' ');
  }
}

extension AppLocalizationsX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales.any(
    (supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<AppLocalizations> load(Locale locale) {
    final languageCode =
        AppLocalizations.supportedLocales.any(
              (supported) => supported.languageCode == locale.languageCode,
            )
            ? locale.languageCode
            : 'fa';
    return SynchronousFuture<AppLocalizations>(
      AppLocalizations(Locale(languageCode)),
    );
  }

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) =>
      false;
}

